# ヴィジョンはジャーヴィスと同じ俳優（ポール・ベタニー）
IMAGES["vision"] = IMAGES["jarvis"]


def image_for(slug, pid):
    """その作品のその人物の顔写真。作品ごとに俳優が違う人物（ハワード・スタークなど）は "作品のslug:人物id" で登録する"""
    key = f"{slug}:{pid}"
    if key in IMAGES:  # None を入れると、その作品では写真なし（頭文字のアイコン）にできる
        return IMAGES[key]
    return IMAGES.get(pid)
