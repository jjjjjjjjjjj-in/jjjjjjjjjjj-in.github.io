# people（人物）:
#   id:     半角英数字（images の キーと同じ）
#   role:   "lead"（中心の2人・いちばん大きい）/ "main"（主要人物）/ "sub"（脇役・小さめ）
#   side:   "hero"（主人公側）/ "neutral"（どちらでもない）/ "villain"（敵側）… アイコンの縁の色になる
